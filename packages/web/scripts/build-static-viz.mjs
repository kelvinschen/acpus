import { rm, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import { build } from "vite";

const root = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(root, "..");
const outDir = join(packageRoot, ".static-viz-build");
const generatedPath = join(packageRoot, "src", "server", "static-viz-assets.generated.ts");

try {
  await rm(outDir, { recursive: true, force: true });
  await build({
    configFile: false,
    root: join(packageRoot, "src", "client"),
    plugins: [react(), tailwindcss()],
    define: {
      "process.env.NODE_ENV": JSON.stringify("production"),
    },
    logLevel: "warn",
    build: {
      outDir,
      emptyOutDir: true,
      cssCodeSplit: false,
      minify: true,
      reportCompressedSize: false,
      lib: {
        entry: join(packageRoot, "src", "client", "static-viz.tsx"),
        name: "AcpusWorkflowViz",
        formats: ["iife"],
        fileName: () => "static-viz.js",
      },
      rolldownOptions: {
        output: {
          assetFileNames: "static-viz[extname]",
        },
      },
    },
  });

  const files = await readdir(outDir);
  const jsFiles = files.filter(file => file.endsWith(".js"));
  const cssFiles = files.filter(file => file.endsWith(".css"));
  if (files.length !== 2 || jsFiles.length !== 1 || cssFiles.length !== 1) {
    throw new Error(`Static viz build must emit exactly one JS and one CSS asset: ${files.join(", ")}`);
  }

  const [js, css] = await Promise.all([
    readFile(join(outDir, jsFiles[0]), "utf8"),
    readFile(join(outDir, cssFiles[0]), "utf8"),
  ]);
  if (js.length === 0 || css.length === 0) {
    throw new Error("Static viz build emitted an empty JS or CSS asset.");
  }
  if (/<\/script(?=[\t\n\f\r />]|$)/iu.test(js) || /<\/style(?=[\t\n\f\r />]|$)/iu.test(css)) {
    throw new Error("Static viz assets cannot close their inline HTML elements.");
  }

  const generated = [
    "/* Generated by packages/web/scripts/build-static-viz.mjs. Do not edit by hand. */",
    `export const staticVizJs: string = ${JSON.stringify(js)};`,
    `export const staticVizCss: string = ${JSON.stringify(css)};`,
    "",
  ].join("\n");

  let current;
  try {
    current = await readFile(generatedPath, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  if (current !== generated) {
    await writeFile(generatedPath, generated);
  }
} finally {
  await rm(outDir, { recursive: true, force: true });
}
